MERGE INTO OOREDOO_CUSTOM_CP_TRANSACTION_JSON t
USING (
    SELECT
        :ACTOR_ID AS ACTOR_ID,
        :SENT_COUNT_JSON AS SENT_COUNT_JSON
    FROM DUAL
) s
ON (t.ACTOR_ID = s.ACTOR_ID
    AND TRUNC(t.SENT_DATE) = TRUNC(SYSDATE)
    )
WHEN MATCHED THEN
    UPDATE SET
        t.SENT_COUNT_JSON = s.SENT_COUNT_JSON
WHEN NOT MATCHED THEN
    INSERT (ACTOR_ID, SENT_COUNT_JSON)
    VALUES (s.ACTOR_ID, s.SENT_COUNT_JSON);