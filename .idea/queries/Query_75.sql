MERGE INTO OOREDOO_CUSTOM_CONTACT_POLICY tgt
USING (
    SELECT :SEGMENT_NAME AS SEGMENT_NAME, :PRIORITY AS PRIORITY, :CHANNEL AS CHANNEL, :MESSAGE_TYPE AS MESSAGE_TYPE,
           :DAILY_LIMIT AS DAILY_LIMIT, :WEEKLY_LIMIT AS WEEKLY_LIMIT, :MONTHLY_LIMIT AS MONTHLY_LIMIT FROM dual
) src
ON (tgt.SEGMENT_NAME = src.SEGMENT_NAME
    AND tgt.CHANNEL = src.CHANNEL
    AND tgt.MESSAGE_TYPE = src.MESSAGE_TYPE)
WHEN MATCHED THEN
    UPDATE SET
               tgt.PRIORITY = src.PRIORITY,
               tgt.DAILY_LIMIT = src.DAILY_LIMIT,
               tgt.WEEKLY_LIMIT = src.WEEKLY_LIMIT,
               tgt.MONTHLY_LIMIT = src.MONTHLY_LIMIT
WHEN NOT MATCHED THEN
    INSERT (PRIORITY, DAILY_LIMIT, WEEKLY_LIMIT, MONTHLY_LIMIT)
    VALUES (src.PRIORITY, src.DAILY_LIMIT, src.WEEKLY_LIMIT, src.MONTHLY_LIMIT);