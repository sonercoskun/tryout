create table ENG.OOREDOO_CUSTOM_CONTACT_POLICY
(
    SEGMENT_NAME  VARCHAR2(128 char) not null,
    PRIORITY      VARCHAR2(10),
    CHANNEL       VARCHAR2(64 char),
    MESSAGE_TYPE  VARCHAR2(64 char),
    DAILY_LIMIT   VARCHAR2(10),
    WEEKLY_LIMIT  VARCHAR2(10),
    MONTHLY_LIMIT VARCHAR2(10)
);
drop table OOREDOO_CUSTOM_CONTACT_POLICY;
TRUNCATE TABLE OOREDOO_CUSTOM_CONTACT_POLICY;
COMMIT

MERGE INTO OOREDOO_CUSTOM_CONTACT_POLICY tgt
USING (
    SELECT :SEGMENT_NAME AS SEGMENT_NAME, :PRIORITY AS PRIORITY, :CHANNEL AS CHANNEL, :MESSAGE_TYPE AS MESSAGE_TYPE, :DAILY_LIMIT AS DAILY_LIMIT, :WEEKLY_LIMIT AS WEEKLY_LIMIT, :MONTHLY_LIMIT AS MONTHLY_LIMIT FROM dual
) src
ON (tgt.SEGMENT_NAME = src.SEGMENT_NAME
    AND tgt.CHANNEL = src.CHANNEL
    AND tgt.MESSAGE_TYPE = src.MESSAGE_TYPE)
WHEN MATCHED THEN
    UPDATE SET
               tgt.PRIORITY = src.PRIORITY,
               tgt.DAILY_LIMIT = src.DAILY_LIMIT,
               tgt.WEEKLY_LIMIT = src.WEEKLY_LIMIT,
               tgt.MONTHLY_LIMIT = src.MONTHLY_LIMIT
WHEN NOT MATCHED THEN
    INSERT (SEGMENT_NAME, PRIORITY, CHANNEL, MESSAGE_TYPE, DAILY_LIMIT, WEEKLY_LIMIT, MONTHLY_LIMIT)
    VALUES (src.SEGMENT_NAME, src.PRIORITY, src.CHANNEL, src.MESSAGE_TYPE, src.DAILY_LIMIT, src.WEEKLY_LIMIT, src.MONTHLY_LIMIT);



